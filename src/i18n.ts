export type TranslationKey = keyof typeof translations.ar;

export function detectInitialLanguage(): AppLanguage {
  const stored = localStorage.getItem('notic-language') as AppLanguage | null;
  if (stored && stored in translations) return stored;

  const candidates = [navigator.language, ...navigator.languages].filter(Boolean);
  const normalized = candidates.map(lang => lang.toLowerCase());

  if (normalized.some(lang => lang.startsWith('ar'))) return 'ar';
  if (normalized.some(lang => lang.startsWith('es'))) return 'es';
  if (normalized.some(lang => lang.startsWith('zh') || lang.includes('cn') || lang.includes('hans'))) return 'zh';
  return 'en';
}

export function translate(language: AppLanguage, key: TranslationKey): string {
  return translations[language]?.[key] ?? translations.en[key] ?? key;
}